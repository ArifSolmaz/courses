# converter.py - Unit conversion utilities for engineering

def celsius_to_fahrenheit(c):
    """Convert Celsius to Fahrenheit."""
    return c * 9 / 5 + 32

def meters_to_feet(m):
    """Convert meters to feet."""
    return m * 3.28084

def kg_to_pounds(kg):
    """Convert kilograms to pounds."""
    return kg * 2.20462
